#!/usr/bin/env python3
"""
PaTHos OS NLP2Code Pipeline
Intent Recognition -> Parse -> Prune -> Compile -> Deploy
"""
import json, os, sys
from pathlib import Path
from typing import Dict, List, Optional

class NLP2CodePipeline:
    def __init__(self, config_path: str):
        with open(config_path, 'r') as f:
            self.config = json.load(f)
        self.intents = self.config.get('intents', [])
        self.agents = self.config.get('agents', {})
        self.skills = self.config.get('skills', {})
    
    def recognize_intent(self, user_input: str) -> Optional[Dict]:
        user_input_lower = user_input.lower()
        for intent in self.intents:
            keywords = intent['intent'].replace('_', ' ').split()
            if any(keyword in user_input_lower for keyword in keywords):
                return intent
        return None
    
    def parse(self, intent: Dict, context: Dict) -> Dict:
        parsed = {
            'intent': intent['intent'],
            'description': intent['description'],
            'source_files': intent.get('source_files', []),
            'parameters': {}
        }
        if 'agent_name' in context:
            parsed['parameters']['agent'] = context['agent_name']
        if 'deployment_target' in context:
            parsed['parameters']['target'] = context['deployment_target']
        return parsed
    
    def prune(self, parsed: Dict) -> Dict:
        pruned = {
            'intent': parsed['intent'],
            'validated_files': [],
            'parameters': parsed['parameters']
        }
        for file in parsed.get('source_files', []):
            if os.path.exists(f"/data/data/com.termux/files/home/{file}"):
                pruned['validated_files'].append(file)
        return pruned
    
    def compile(self, pruned: Dict, language: str = 'python') -> str:
        if language == 'python':
            return self._compile_python(pruned)
        elif language == 'java':
            return self._compile_java(pruned)
        elif language == 'cpp':
            return self._compile_cpp(pruned)
        elif language == 'julia':
            return self._compile_julia(pruned)
        return self._compile_python(pruned)
    
    def _compile_python(self, pruned: Dict) -> str:
        return f"""#!/usr/bin/env python3
# Auto-generated by PaTHos NLP2Code Pipeline
# Intent: {pruned['intent']}
import subprocess, sys
def execute():
    print(f"Executing: {pruned['intent']}")
    for file in {pruned['validated_files']}:
        if file.endswith('.sh'):
            subprocess.run(['bash', file], check=True)
        elif file.endswith('.py'):
            subprocess.run([sys.executable, file], check=True)
    print(f"✓ {pruned['intent']} completed successfully")
if __name__ == '__main__':
    execute()
"""
    
    def _compile_java(self, pruned: Dict) -> str:
        return f"""// Auto-generated by PaTHos NLP2Code Pipeline
// Intent: {pruned['intent']}
public class {pruned['intent'].replace('_', ' ').title().replace(' ', '')} {{
    public static void execute() {{
        System.out.println("Executing: {pruned['intent']}");
        System.out.println("✓ {pruned['intent']} completed successfully");
    }}
    public static void main(String[] args) {{ execute(); }}
}}
"""
    
    def _compile_cpp(self, pruned: Dict) -> str:
        return f"""// Auto-generated by PaTHos NLP2Code Pipeline
// Intent: {pruned['intent']}
#include <iostream>
void execute() {{
    std::cout << "Executing: {pruned['intent']}" << std::endl;
    std::cout << "✓ {pruned['intent']} completed successfully" << std::endl;
}}
int main() {{ execute(); return 0; }}
"""
    
    def _compile_julia(self, pruned: Dict) -> str:
        return f"""# Auto-generated by PaTHos NLP2Code Pipeline
# Intent: {pruned['intent']}
function execute()
    println("Executing: {pruned['intent']}")
    println("✓ {pruned['intent']} completed successfully")
end
execute()
"""
    
    def deploy(self, compiled_code: str, output_path: str):
        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)
        with open(output_file, 'w') as f:
            f.write(compiled_code)
        print(f"✓ Deployed to: {output_path}")

def main():
    if len(sys.argv) < 2:
        print("Usage: pathos_nlp2code.py <user_input>")
        sys.exit(1)
    user_input = ' '.join(sys.argv[1:])
    pipeline = NLP2CodePipeline('/data/data/com.termux/files/home/constellation25/nlp2code-package/training-data/manifest.json')
    intent = pipeline.recognize_intent(user_input)
    if not intent:
        print(f"❌ No intent recognized for: {user_input}")
        sys.exit(1)
    print(f"✓ Recognized intent: {intent['intent']}")
    parsed = pipeline.parse(intent, {})
    print(f"✓ Parsed: {parsed['intent']}")
    pruned = pipeline.prune(parsed)
    print(f"✓ Pruned: {len(pruned['validated_files'])} files validated")
    compiled = pipeline.compile(pruned, 'python')
    print(f"✓ Compiled to Python")
    output_path = f"/data/data/com.termux/files/home/constellation25/build/output/{intent['intent']}.py"
    pipeline.deploy(compiled, output_path)

if __name__ == '__main__':
    main()
