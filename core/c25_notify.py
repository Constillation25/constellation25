#!/data/data/com.termux/files/usr/bin/env python3
import subprocess
import smtplib
import os
import sys
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from datetime import datetime

def notify_completion(task_id, agent_name, details, success=True):
    status = "✅ COMPLETE" if success else "❌ FAILED"
    toast_msg = f"C25: {agent_name} {status} - {task_id}"
    
    # 1. TERMUX API TOAST
    try:
        subprocess.run(["termux-toast", toast_msg], check=True, capture_output=True)
    except Exception as e:
        print(f"[WARN] Termux Toast failed: {e}")

    # 2. EMAIL NOTIFICATION TO KRE8TIVE KONCEPTZ
    recipient = "kre8tivekonceptz@gmail.com"
    subject = f"[C25 {status}] Agent: {agent_name} | Task: {task_id}"
    
    body = f"""
C25 SOVEREIGN AI ECOSYSTEM - TASK COMPLETION REPORT
---------------------------------------------------
Task ID:      {task_id}
Agent:        {agent_name}
Status:       {status}
Timestamp:    {datetime.now().strftime('%Y-%m-%d %H:%M:%S %Z')}

Completion Details:
{details}
---------------------------------------------------
Generated by C25 Notification Module
"""

    msg = MIMEMultipart()
    msg['From'] = "c25_agent@kre8tive.local"
    msg['To'] = recipient
    msg['Subject'] = subject
    msg.attach(MIMEText(body, 'plain'))

    try:
        # NOTE: Replace 'YOUR_GMAIL_APP_PASSWORD' with your actual Gmail App Password
        # Go to Google Account -> Security -> App Passwords to generate one.
        smtp_server = "smtp.gmail.com"
        smtp_port = 587
        sender_email = "YOUR_GMAIL_ADDRESS@gmail.com" # Replace with your sending address
        sender_password = "YOUR_GMAIL_APP_PASSWORD"   # Replace with your App Password
        
        server = smtplib.SMTP(smtp_server, smtp_port)
        server.starttls()
        server.login(sender_email, sender_password)
        server.send_message(msg)
        server.quit()
        print(f"[INFO] Email notification sent to {recipient}")
    except Exception as e:
        print(f"[WARN] Email notification failed (Check SMTP credentials): {e}")

if __name__ == "__main__":
    if len(sys.argv) >= 4:
        notify_completion(sys.argv[1], sys.argv[2], sys.argv[3], success=(len(sys.argv) > 4 and sys.argv[4] == "SUCCESS"))
    else:
        print("Usage: c25_notify.py <task_id> <agent_name> <details> [SUCCESS|FAILED]")
